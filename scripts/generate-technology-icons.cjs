const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");
const catalogue = require("devicon/devicon.json");
const normalize = (value) =>
  value
    .toLowerCase()
    .replace(/\+/g, "plus")
    .replace(/#/g, "sharp")
    .replace(/[^a-z0-9]/g, "");
const imports = [],
  entries = new Map();
for (const icon of catalogue) {
  const variant = ["original", "plain", "line"].find((v) =>
    icon.versions.svg.includes(v),
  );
  if (!variant) continue;
  const filename = `devicon/icons/${icon.name}/${icon.name}-${variant}.svg`;
  if (!fs.existsSync(path.join(root, "node_modules", filename))) continue;
  const svg = fs.readFileSync(
    path.join(root, "node_modules", filename),
    "utf8",
  );
  if (
    /<script|<foreignObject|\son\w+\s*=|(?:href|src)\s*=\s*["'](?:https?:|\/\/)|url\(\s*["']?(?:https?:|\/\/)/i.test(
      svg,
    )
  )
    throw new Error(`Icon contains active or external resources: ${filename}`);
  const variable = `icon${imports.length}`;
  imports.push(
    `import ${variable} from ${JSON.stringify(filename + "?url&no-inline")};`,
  );
  for (const name of [icon.name, ...icon.altnames])
    if (!entries.has(normalize(name))) entries.set(normalize(name), variable);
}
const aliases = {
  ".NET": "dotnetcore",
  "ASP.NET Core": "dotnetcore",
  "Entity Framework Core": "dotnetcore",
  Vue: "vuejs",
  Nuxt: "nuxtjs",
  "Next.js": "nextjs",
  NestJS: "nestjs",
  Angular: "angular",
  Svelte: "svelte",
  Rust: "rust",
  Go: "go",
  "Ruby on Rails": "rails",
  "Tailwind CSS": "tailwindcss",
  "Microsoft SQL Server": "microsoftsqlserver",
  MSSQL: "microsoftsqlserver",
  Postgres: "postgresql",
  "C++": "cplusplus",
  "C#": "csharp",
  "F#": "fsharp",
  "Visual Basic": "visualbasic",
  Shell: "bash",
  "Shell script": "bash",
};
for (const [alias, slug] of Object.entries(aliases))
  if (entries.has(normalize(slug)))
    entries.set(normalize(alias), entries.get(normalize(slug)));
const output =
  "// Generated by scripts/generate-technology-icons.cjs from Devicon (MIT).\n// Icons are bundled locally. Unrecognized technologies keep their dot.\n" +
  imports.join("\n") +
  "\nexport const technologyIcons: Readonly<Record<string, string>> = {\n" +
  [...entries]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, variable]) => `  ${JSON.stringify(name)}: ${variable},`)
    .join("\n") +
  "\n};\n";
fs.writeFileSync(path.join(root, "src/technology-icons.generated.ts"), output);
console.log(
  `Generated ${imports.length} local icons and ${entries.size} technology names.`,
);

fs.mkdirSync(path.join(root, "public/licenses"), { recursive: true });
fs.copyFileSync(
  path.join(root, "node_modules/devicon/LICENSE"),
  path.join(root, "public/licenses/Devicon.txt"),
);
